def write_manifest(path: Path, case: ExactOverwriteCase, checkpoint_inc: int) -> None:
    text = f"""# Stage 16N-R3E Exact Overwrite Case

- Case: `{case.case_id}`
- Job: `{case.job}`
- Oldjob: `{case.oldjob}`
- Restart read: `STEP={case.checkpoint_cycle}, INC={checkpoint_inc}`
- Continuation: `{case.checkpoint_cycle} -> {case.target_cycle}`
- Overwrite trigger: `JSTEP(1)={case.target_step}`, `KINC=0`, `TIME(1)=0`, `TIME(2)~={case.checkpoint_cycle}`
- Exact state source: `{case.oldjob}.odb`, cycle `{case.checkpoint_cycle}`
- Overwritten variables: `STATEV(1:25)`
- Not table-overwritten: `STATEV(26:27)`
- Production resources: `select=1:ncpus=16:mpiprocs=1:ompthreads=16:mem=90gb`, `walltime=24:00:00`
"""
    path.write_text(text, encoding="utf-8", newline="\n")


def prepare_cases(cases: tuple[ExactOverwriteCase, ...]) -> None:
    for required in (BASE_UMAT, EXTRACTOR, EXACT_STATE_EXTRACTOR, COMPARE):
        if not required.exists():
            raise FileNotFoundError(required)
    R3E_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for case in cases:
        run_dir = case.run_dir
        run_dir.mkdir(parents=True, exist_ok=True)
        checkpoint_inc = parse_checkpoint_increment(case.source_dir / f"{case.oldjob}.sta", case.checkpoint_cycle)
        write_restart_deck(run_dir / f"{case.job}.inp", case, checkpoint_inc)
        write_overwrite_umat(run_dir / "stage16n_r3_exact_overwrite_umat.for")
        write_link_script(run_dir / "link_restart_sources.sh", case)
        write_runner(run_dir / "run_stage16n_r3e_exact_overwrite_hpc.sh", case)
        write_pbs(run_dir / f"submit_{case.job}.pbs", case)
        write_manifest(run_dir / "STAGE16N_R3E_CASE_MANIFEST.md", case, checkpoint_inc)
        rows.append(
            {
                "case_id": case.case_id,
                "job": case.job,
                "oldjob": case.oldjob,
                "checkpoint_cycle": case.checkpoint_cycle,
                "checkpoint_inc": checkpoint_inc,
                "target_cycle": case.target_cycle,
                "target_step": case.target_step,
            }
        )
        print(f"Prepared {run_dir}")
    with (R3E_DIR / "stage16n_r3e_exact_overwrite_cases.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=[
                "case_id",
                "job",
                "oldjob",
                "checkpoint_cycle",
                "checkpoint_inc",
                "target_cycle",
                "target_step",
            ],
        )
        writer.writeheader()
        writer.writerows(rows)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--case", choices=["all", "R3E1", "R3E2"], default="all")
    args = parser.parse_args()
    if args.case == "R3E1":
        selected = (CASES[0],)
    elif args.case == "R3E2":
        selected = (CASES[1],)
    else:
        selected = CASES
    prepare_cases(selected)


if __name__ == "__main__":
    main()
