C Stage 16N exact state reinjection hooks.
C
C The preparation script copies these hooks into a case-specific UMAT file after
C replacing __STATE_FILE__ with the local CSV state file.  The CSV columns are:
C NOEL,NPT,S1,S2,S3,S4,S5,S6,SDV1,...,SDV27

      SUBROUTINE STAGE16N_LOAD_STATE()
      INCLUDE 'ABA_PARAM.INC'
      INTEGER MAXREC,NSTAGEV
      PARAMETER (MAXREC=40000,NSTAGEV=27)
      INTEGER LOADED,NREC,ELABEL(MAXREC),IPLABEL(MAXREC)
      DOUBLE PRECISION STAB(6,MAXREC),VTAB(NSTAGEV,MAXREC)
      COMMON /STAGE16N_STATE/ LOADED,NREC,ELABEL,IPLABEL,STAB,VTAB
      INTEGER IOS,I,J,NOEL,NPT
      DOUBLE PRECISION S1,S2,S3,S4,S5,S6
      DOUBLE PRECISION V1,V2,V3,V4,V5,V6,V7,V8,V9,V10
      DOUBLE PRECISION V11,V12,V13,V14,V15,V16,V17,V18,V19,V20
      DOUBLE PRECISION V21,V22,V23,V24,V25,V26,V27
      CHARACTER*512 HEADER

      IF (LOADED.EQ.1) RETURN

      NREC=0
      OPEN(UNIT=77,FILE='__STATE_FILE__',STATUS='OLD',IOSTAT=IOS)
      IF (IOS.NE.0) THEN
        WRITE(6,*) 'STAGE16N ERROR: cannot open state file __STATE_FILE__'
        CALL XIT
      END IF

      READ(77,'(A)',IOSTAT=IOS) HEADER
 10   CONTINUE
      READ(77,*,IOSTAT=IOS) NOEL,NPT,S1,S2,S3,S4,S5,S6,
     1 V1,V2,V3,V4,V5,V6,V7,V8,V9,V10,
     2 V11,V12,V13,V14,V15,V16,V17,V18,V19,V20,
     3 V21,V22,V23,V24,V25,V26,V27
      IF (IOS.NE.0) GOTO 20
      NREC=NREC+1
      IF (NREC.GT.MAXREC) THEN
        WRITE(6,*) 'STAGE16N ERROR: MAXREC exceeded in state reader'
        CALL XIT
      END IF
      ELABEL(NREC)=NOEL
      IPLABEL(NREC)=NPT
      STAB(1,NREC)=S1
      STAB(2,NREC)=S2
      STAB(3,NREC)=S3
      STAB(4,NREC)=S4
      STAB(5,NREC)=S5
      STAB(6,NREC)=S6
      VTAB(1,NREC)=V1
      VTAB(2,NREC)=V2
      VTAB(3,NREC)=V3
      VTAB(4,NREC)=V4
      VTAB(5,NREC)=V5
      VTAB(6,NREC)=V6
      VTAB(7,NREC)=V7
      VTAB(8,NREC)=V8
      VTAB(9,NREC)=V9
      VTAB(10,NREC)=V10
      VTAB(11,NREC)=V11
      VTAB(12,NREC)=V12
      VTAB(13,NREC)=V13
      VTAB(14,NREC)=V14
      VTAB(15,NREC)=V15
      VTAB(16,NREC)=V16
      VTAB(17,NREC)=V17
      VTAB(18,NREC)=V18
      VTAB(19,NREC)=V19
      VTAB(20,NREC)=V20
      VTAB(21,NREC)=V21
      VTAB(22,NREC)=V22
      VTAB(23,NREC)=V23
      VTAB(24,NREC)=V24
      VTAB(25,NREC)=V25
      VTAB(26,NREC)=V26
      VTAB(27,NREC)=V27
      GOTO 10

 20   CONTINUE
      CLOSE(77)
      LOADED=1
      WRITE(6,*) 'STAGE16N loaded reinjection records:', NREC
      RETURN
      END

      SUBROUTINE STAGE16N_FIND(NOEL,NPT,IDX)
      INCLUDE 'ABA_PARAM.INC'
      INTEGER MAXREC,NSTAGEV
      PARAMETER (MAXREC=40000,NSTAGEV=27)
      INTEGER LOADED,NREC,ELABEL(MAXREC),IPLABEL(MAXREC)
      DOUBLE PRECISION STAB(6,MAXREC),VTAB(NSTAGEV,MAXREC)
      COMMON /STAGE16N_STATE/ LOADED,NREC,ELABEL,IPLABEL,STAB,VTAB
      INTEGER NOEL,NPT,IDX,I

      CALL STAGE16N_LOAD_STATE()
      IDX=0
      DO I=1,NREC
        IF (ELABEL(I).EQ.NOEL .AND. IPLABEL(I).EQ.NPT) THEN
          IDX=I
          RETURN
        END IF
      END DO
      RETURN
      END

      BLOCK DATA STAGE16N_STATE_INIT
      INTEGER MAXREC,NSTAGEV
      PARAMETER (MAXREC=40000,NSTAGEV=27)
      INTEGER LOADED,NREC,ELABEL(MAXREC),IPLABEL(MAXREC)
      DOUBLE PRECISION STAB(6,MAXREC),VTAB(NSTAGEV,MAXREC)
      COMMON /STAGE16N_STATE/ LOADED,NREC,ELABEL,IPLABEL,STAB,VTAB
      DATA LOADED /0/
      DATA NREC /0/
      END

      SUBROUTINE SIGINI(SIGMA,COORDS,NTENS,NCRDS,NOEL,NPT,
     1 LAYER,KSPT,LREBAR,NAMES)
      INCLUDE 'ABA_PARAM.INC'
      INTEGER MAXREC,NSTAGEV
      PARAMETER (MAXREC=40000,NSTAGEV=27)
      INTEGER LOADED,NREC,ELABEL(MAXREC),IPLABEL(MAXREC)
      DOUBLE PRECISION STAB(6,MAXREC),VTAB(NSTAGEV,MAXREC)
      COMMON /STAGE16N_STATE/ LOADED,NREC,ELABEL,IPLABEL,STAB,VTAB
      DIMENSION SIGMA(NTENS),COORDS(NCRDS)
      CHARACTER*80 NAMES(2)
      INTEGER IDX,I

      CALL STAGE16N_FIND(NOEL,NPT,IDX)
      IF (IDX.EQ.0) THEN
        WRITE(6,*) 'STAGE16N SIGINI missing NOEL,NPT:', NOEL,NPT
        CALL XIT
      END IF
      DO I=1,NTENS
        IF (I.LE.6) SIGMA(I)=STAB(I,IDX)
      END DO
      RETURN
      END

      SUBROUTINE SDVINI(STATEV,COORDS,NSTATV,NCRDS,NOEL,NPT,
     1 LAYER,KSPT)
      INCLUDE 'ABA_PARAM.INC'
      INTEGER MAXREC,NSTAGEV
      PARAMETER (MAXREC=40000,NSTAGEV=27)
      INTEGER LOADED,NREC,ELABEL(MAXREC),IPLABEL(MAXREC)
      DOUBLE PRECISION STAB(6,MAXREC),VTAB(NSTAGEV,MAXREC)
      COMMON /STAGE16N_STATE/ LOADED,NREC,ELABEL,IPLABEL,STAB,VTAB
      DIMENSION STATEV(NSTATV),COORDS(NCRDS)
      INTEGER IDX,I

      CALL STAGE16N_FIND(NOEL,NPT,IDX)
      IF (IDX.EQ.0) THEN
        WRITE(6,*) 'STAGE16N SDVINI missing NOEL,NPT:', NOEL,NPT
        CALL XIT
      END IF
      DO I=1,NSTATV
        IF (I.LE.NSTAGEV) STATEV(I)=VTAB(I,IDX)
      END DO
      RETURN
      END
