#!/usr/bin/env python3
"""Generate a Stage 16N-R4Q restart-continuation deck for one adaptive block."""

import argparse
from pathlib import Path


def step_block(cycle, final_cycle):
    lines = [
        "*STEP, NAME=CYCLE_{:04d}, NLGEOM=NO, INC=160".format(cycle),
        "*STATIC",
        "0.005, 1.0, 1.0E-08, 0.025",
    ]
    if cycle == final_cycle:
        lines.append("*RESTART, WRITE, FREQUENCY=1")
    lines.extend(
        [
            "*BOUNDARY, AMPLITUDE=AMP_ONE_CYCLE",
            "RIGHT_EDGE, 1, 1, 0.10",
            "*OUTPUT, HISTORY, FREQUENCY=1",
            "*NODE OUTPUT, NSET=RIGHT_EDGE",
            "U1, RF1",
        ]
    )
    if cycle == final_cycle:
        lines.extend(
            [
                "*OUTPUT, FIELD, NUMBER INTERVAL=4",
                "*NODE OUTPUT",
                "U, RF",
                "*ELEMENT OUTPUT",
                "S, SDV",
            ]
        )
    lines.append("*END STEP")
    return lines


def write_deck(path, old_step, old_inc, solved_start, block_end, title):
    lines = [
        "** Stage 16N-R4Q long adaptive chain continuation",
        "** {}".format(title),
        "** Generated by stage16n_make_r4q_restart_deck.py",
        "** Restart is written only at the block end for the next chain block.",
        title,
        "*RESTART, READ, STEP={}, INC={}".format(old_step, old_inc),
    ]
    for cycle in range(solved_start, block_end + 1):
        lines.extend(step_block(cycle, block_end))
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--old-step", type=int, required=True)
    parser.add_argument("--old-inc", type=int, required=True)
    parser.add_argument("--solved-start", type=int, required=True)
    parser.add_argument("--block-end", type=int, required=True)
    parser.add_argument("--title", required=True)
    return parser.parse_args()


def main():
    args = parse_args()
    if args.solved_start > args.block_end:
        raise SystemExit("solved-start must be <= block-end")
    write_deck(args.output, args.old_step, args.old_inc, args.solved_start, args.block_end, args.title)
    print("Wrote {}".format(args.output))


if __name__ == "__main__":
    main()

