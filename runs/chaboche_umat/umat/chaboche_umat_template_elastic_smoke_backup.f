      SUBROUTINE UMAT(STRESS,STATEV,DDSDDE,SSE,SPD,SCD,
     1 RPL,DDSDDT,DRPLDE,DRPLDT,STRAN,DSTRAN,TIME,DTIME,
     2 TEMP,DTEMP,PREDEF,DPRED,CMNAME,NDI,NSHR,NTENS,NSTATV,
     3 PROPS,NPROPS,COORDS,DROT,PNEWDT,CELENT,DFGRD0,DFGRD1,
     4 NOEL,NPT,LAYER,KSPT,JSTEP,KINC)

      INCLUDE 'ABA_PARAM.INC'

      CHARACTER*80 CMNAME
      DIMENSION STRESS(NTENS),STATEV(NSTATV),
     1 DDSDDE(NTENS,NTENS),DDSDDT(NTENS),DRPLDE(NTENS),
     2 STRAN(NTENS),DSTRAN(NTENS),TIME(2),PREDEF(1),DPRED(1),
     3 PROPS(NPROPS),COORDS(3),DROT(3,3),DFGRD0(3,3),
     4 DFGRD1(3,3),JSTEP(4)

      DOUBLE PRECISION E,NU,MU,LAM
      INTEGER I,J

      E  = PROPS(1)
      NU = PROPS(2)

      MU  = E/(2.D0*(1.D0+NU))
      LAM = E*NU/((1.D0+NU)*(1.D0-2.D0*NU))

      DO I=1,NTENS
        DO J=1,NTENS
          DDSDDE(I,J)=0.D0
        END DO
      END DO

      DDSDDE(1,1)=LAM+2.D0*MU
      DDSDDE(2,2)=LAM+2.D0*MU
      DDSDDE(3,3)=LAM+2.D0*MU
      DDSDDE(1,2)=LAM
      DDSDDE(1,3)=LAM
      DDSDDE(2,1)=LAM
      DDSDDE(2,3)=LAM
      DDSDDE(3,1)=LAM
      DDSDDE(3,2)=LAM

      IF (NTENS.GE.4) DDSDDE(4,4)=MU
      IF (NTENS.GE.5) DDSDDE(5,5)=MU
      IF (NTENS.GE.6) DDSDDE(6,6)=MU

      DO I=1,NTENS
        DO J=1,NTENS
          STRESS(I)=STRESS(I)+DDSDDE(I,J)*DSTRAN(J)
        END DO
      END DO

C     Store something visible in SDV1 to prove STATEV output still works
      IF (NSTATV.GE.1) STATEV(1)=STRAN(1)+DSTRAN(1)

      RETURN
      END
